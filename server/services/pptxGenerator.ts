import PptxGenJS from 'pptxgenjs';
import type { PresentationDeck, SlideThemeId } from '../../src/types/paperwise.ts';

interface ThemePalette {
  bg: string;
  titleBg: string;
  accent: string;
  secondaryAccent: string;
  heading: string;
  body: string;
  muted: string;
  cardBg: string;
  cardBorder: string;
  titleText: string;
}

const THEMES: Record<SlideThemeId, ThemePalette> = {
  'oxford-navy': {
    bg: 'F8FAFC',
    titleBg: '0F172A',
    accent: '3B82F6',
    secondaryAccent: '6366F1',
    heading: '0F172A',
    body: '1E293B',
    muted: '64748B',
    cardBg: 'FFFFFF',
    cardBorder: 'CBD5E1',
    titleText: 'F8FAFC',
  },
  'slate-academic': {
    bg: 'FFFFFF',
    titleBg: '1E293B',
    accent: '2563EB',
    secondaryAccent: '475569',
    heading: '0F172A',
    body: '334155',
    muted: '64748B',
    cardBg: 'F1F5F9',
    cardBorder: 'CBD5E1',
    titleText: 'FFFFFF',
  },
  'violet-research': {
    bg: 'F8FAFC',
    titleBg: '17153B',
    accent: '7C3AED',
    secondaryAccent: '2563EB',
    heading: '1E1B4B',
    body: '1E293B',
    muted: '64748B',
    cardBg: 'FFFFFF',
    cardBorder: 'DDD6FE',
    titleText: 'F8FAFC',
  },
};

export async function buildPptxBuffer(deck: PresentationDeck): Promise<Buffer> {
  const pptx = new PptxGenJS();
  pptx.layout = 'LAYOUT_WIDE'; // 13.333 x 7.5 inches (16:9)
  pptx.title = deck.paperTitle;
  pptx.subject = 'Generated by PAPERWISE AI';
  pptx.author = 'PAPERWISE AI Slide-Generator Agent';

  const palette = THEMES[deck.theme] ?? THEMES['oxford-navy'];

  for (const slideData of deck.slides) {
    const slide = pptx.addSlide();
    const isTitleSlide = slideData.slideNumber === 1;

    if (isTitleSlide) {
      slide.background = { color: palette.titleBg };
      // Accent rule
      slide.addShape(pptx.ShapeType.rect, {
        x: 0.9,
        y: 1.3,
        w: 1.4,
        h: 0.08,
        fill: { color: palette.accent },
      });

      slide.addText(slideData.sectionType || 'RESEARCH PRESENTATION', {
        x: 0.9,
        y: 1.55,
        w: 11.5,
        h: 0.35,
        fontFace: 'Calibri',
        fontSize: 12,
        bold: true,
        color: palette.accent,
        charSpacing: 2,
      });

      slide.addText(slideData.title || deck.paperTitle, {
        x: 0.9,
        y: 2.05,
        w: 11.5,
        h: 1.7,
        fontFace: 'Calibri',
        fontSize: 32,
        bold: true,
        color: palette.titleText,
        valign: 'top',
      });

      if (slideData.subtitle || deck.sourceInfo) {
        slide.addText(slideData.subtitle || deck.sourceInfo, {
          x: 0.9,
          y: 3.9,
          w: 11.5,
          h: 0.8,
          fontFace: 'Calibri',
          fontSize: 16,
          color: 'CBD5E1',
        });
      }

      if (slideData.bullets.length > 0) {
        slide.addText(
          slideData.bullets.slice(0, 4).map((b) => ({
            text: b,
            options: { bullet: true, breakLine: true },
          })),
          {
            x: 0.9,
            y: 4.9,
            w: 11.5,
            h: 1.8,
            fontFace: 'Calibri',
            fontSize: 14,
            color: 'E2E8F0',
            paraSpaceAfter: 6,
          }
        );
      }

      slide.addText(`Source: ${deck.sourceInfo}`, {
        x: 0.9,
        y: 6.9,
        w: 11.5,
        h: 0.3,
        fontFace: 'Calibri',
        fontSize: 10,
        color: '94A3B8',
      });
    } else {
      slide.background = { color: palette.bg };

      // Top header band
      slide.addShape(pptx.ShapeType.rect, {
        x: 0,
        y: 0,
        w: 13.333,
        h: 0.1,
        fill: { color: palette.accent },
      });

      slide.addText(`${slideData.sectionType.toUpperCase()}  ·  ${slideData.pageReferences}`, {
        x: 0.75,
        y: 0.35,
        w: 10,
        h: 0.3,
        fontFace: 'Calibri',
        fontSize: 10,
        bold: true,
        color: palette.accent,
      });

      slide.addText(slideData.title, {
        x: 0.75,
        y: 0.65,
        w: 11.8,
        h: 0.65,
        fontFace: 'Calibri',
        fontSize: 24,
        bold: true,
        color: palette.heading,
      });

      // Divider line
      slide.addShape(pptx.ShapeType.rect, {
        x: 0.75,
        y: 1.35,
        w: 11.8,
        h: 0.02,
        fill: { color: palette.cardBorder },
      });

      const hasChart = Array.isArray(slideData.chartData) && slideData.chartData.length >= 2;
      const hasDiagram = Array.isArray(slideData.diagramNodes) && slideData.diagramNodes.length >= 2;

      const bulletWidth = hasChart ? 6.2 : 11.6;
      const bulletHeight = hasDiagram && !hasChart ? 3.2 : 4.9;

      if (slideData.bullets.length > 0) {
        slide.addText(
          slideData.bullets.map((b) => ({
            text: b,
            options: { bullet: { indent: 14 }, breakLine: true },
          })),
          {
            x: 0.75,
            y: 1.6,
            w: bulletWidth,
            h: bulletHeight,
            fontFace: 'Calibri',
            fontSize: 16,
            color: palette.body,
            valign: 'top',
            paraSpaceAfter: 12,
          }
        );
      }

      if (hasChart && slideData.chartData) {
        const labels = slideData.chartData.map((d) => d.label);
        const values = slideData.chartData.map((d) => d.value);
        slide.addChart(
          pptx.ChartType.bar,
          [
            {
              name: slideData.chartData[0]?.unit || 'Metric',
              labels,
              values,
            },
          ],
          {
            x: 7.25,
            y: 1.65,
            w: 5.3,
            h: 4.5,
            barDir: 'col',
            chartColors: [palette.accent, palette.secondaryAccent],
            showValue: true,
            showLegend: false,
            catAxisLabelFontSize: 10,
            valAxisLabelFontSize: 10,
          }
        );
      } else if (hasDiagram && slideData.diagramNodes) {
        const nodes = slideData.diagramNodes.slice(0, 5);
        const totalW = 11.8;
        const gap = 0.25;
        const boxW = (totalW - gap * (nodes.length - 1)) / nodes.length;
        const boxY = 5.05;

        nodes.forEach((node, idx) => {
          const boxX = 0.75 + idx * (boxW + gap);
          slide.addShape(pptx.ShapeType.roundRect, {
            x: boxX,
            y: boxY,
            w: boxW,
            h: 1.15,
            rectRadius: 0.08,
            fill: { color: palette.cardBg },
            line: { color: idx === nodes.length - 1 ? palette.accent : palette.cardBorder, width: 1.5 },
          });
          slide.addText(`${idx + 1}. ${node}`, {
            x: boxX + 0.1,
            y: boxY + 0.1,
            w: boxW - 0.2,
            h: 0.95,
            fontFace: 'Calibri',
            fontSize: 11.5,
            bold: true,
            color: palette.heading,
            align: 'center',
            valign: 'middle',
          });
        });
      }

      // Slide footer
      slide.addText(
        `${deck.paperTitle.slice(0, 85)}${deck.paperTitle.length > 85 ? '…' : ''}`,
        {
          x: 0.75,
          y: 6.95,
          w: 9.5,
          h: 0.3,
          fontFace: 'Calibri',
          fontSize: 9.5,
          color: palette.muted,
        }
      );

      slide.addText(`Slide ${slideData.slideNumber} / ${deck.slideCount}`, {
        x: 10.6,
        y: 6.95,
        w: 1.95,
        h: 0.3,
        fontFace: 'Calibri',
        fontSize: 9.5,
        color: palette.muted,
        align: 'right',
      });
    }

    if (slideData.speakerNotes) {
      slide.addNotes(slideData.speakerNotes);
    }
  }

  const output = await pptx.write({ outputType: 'nodebuffer' });
  return Buffer.isBuffer(output) ? output : Buffer.from(output as ArrayBuffer);
}
